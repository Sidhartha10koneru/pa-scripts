q = pd.read_parquet(p, columns=["CSN","FINAL_CPT","QUANTITY","GROUP_LABEL","FILING_ORDER_C"], filesystem=pafs.S3FileSystem())
q = q[pd.to_numeric(q.FILING_ORDER_C, errors="coerce") == 1]
q["units"] = pd.to_numeric(q.QUANTITY, errors="coerce")
print("missing:", f"{q.units.isna().mean():.1%}", "| distinct:", q.units.nunique())
print(q.units.describe(percentiles=[.5,.75,.9,.99]).round(2).to_string())
print("share by units:", (q.units.clip(upper=10).value_counts(normalize=True).sort_index().round(3)).to_dict())
q["pa"] = q.GROUP_LABEL.astype(str).str.upper().eq("TRUE")
print("PA rate by units:", q.groupby(q.units.clip(upper=10)).pa.mean().round(3).to_dict())
top = q.groupby("FINAL_CPT", observed=True).units.agg(["count","nunique","max"]).query("count > 1000").sort_values("nunique", ascending=False).head(15)
print(top.to_string())
